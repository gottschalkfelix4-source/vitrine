def test_upload_ueber_die_oberflaeche(client):
    c, _ = client
    assert c.get("/api/cookies").json()["vorhanden"] is False

    antwort = c.post("/api/cookies", files={"datei": ("cookies.txt", GUELTIG, "text/plain")})
    assert antwort.status_code == 200
    daten = antwort.json()
    assert daten["brauchbar"] is True
    assert daten["angemeldet"] is True
    assert daten["vorhanden"] is True

    assert c.get("/api/cookies").json()["angemeldet"] is True


def test_upload_einer_untauglichen_datei_wird_abgelehnt(client):
    c, _ = client
    antwort = c.post(
        "/api/cookies", files={"datei": ("cookies.json", b'[{"a": 1}]', "application/json")}
    )
    assert antwort.status_code == 422
    # Die Begruendung muss durchgereicht werden - eine nackte 422 hilft niemandem.
    assert "JSON" in antwort.json()["detail"]


def test_loeschen(client):
    c, _ = client
    c.post("/api/cookies", files={"datei": ("cookies.txt", GUELTIG, "text/plain")})
    assert c.delete("/api/cookies").status_code == 200
    assert c.get("/api/cookies").json()["vorhanden"] is False
    assert c.delete("/api/cookies").status_code == 404


