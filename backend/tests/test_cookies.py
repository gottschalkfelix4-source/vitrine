def test_probelauf_meldet_fortbestehende_abweisung(client, monkeypatch):
    """Die aussagekraeftigste Antwort: Cookies hinterlegt und trotzdem
    abgewiesen - dann sind sie rotiert oder abgemeldet exportiert."""
    from app.services import drosselung, ytdlp

    c, _ = client

    def abgewiesen(_vid):
        raise ytdlp.Gedrosselt("Sign in to confirm you're not a bot")

    monkeypatch.setattr(ytdlp, "fetch_video_info", abgewiesen)
    daten = c.post("/api/cookies/test").json()
    assert daten["erfolg"] is False
    assert "rotiert" in daten["meldung"]
    # Und der Fehlversuch zaehlt wie jeder andere: Die Pause greift.
    assert drosselung.wartezeit() > 0


def test_probelauf_feuert_nicht_in_eine_laufende_pause(client, monkeypatch):
    """Sonst waere das Ergebnis unabhaengig von den Cookies ein Fehlschlag -
    und die Anfrage verlaengerte die Sperre, die man gerade abwartet."""
    from app.services import drosselung, ytdlp

    c, _ = client
    gerufen = []
    monkeypatch.setattr(ytdlp, "fetch_video_info", lambda vid: gerufen.append(vid))

    drosselung.melden("nicht als Bot bestaetigt")
    daten = c.post("/api/cookies/test").json()

    assert daten["pausiert"] is True
    assert daten["erfolg"] is False
    assert gerufen == [], "waehrend der Pause darf keine Anfrage rausgehen"


def test_probelauf_nimmt_ein_video_aus_der_eigenen_warteschlange(client, monkeypatch):
    """Ein Test an einem fremden Video sagt wenig. Interessant ist, ob genau
    die Videos durchkommen, die gerade nicht durchkommen."""
    from app.models import Channel, Video, VideoStatus
    from app.services import ytdlp

    c, db = client
    db.add(Channel(id="UCtest", name="Testkanal"))
    db.add(Video(id="meinvideo", channel_id="UCtest", title="X", status=VideoStatus.FAILED))
    db.commit()

    monkeypatch.setattr(ytdlp, "fetch_video_info", lambda vid: {"title": vid, "formats": []})
    assert c.post("/api/cookies/test").json()["video_id"] == "meinvideo"
