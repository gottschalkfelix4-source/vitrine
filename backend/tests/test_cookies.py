"""Der Cookie-Assistent.

Die Pruefung ist hier der wertvolle Teil, nicht der Upload. Eine Cookie-Datei
scheitert auf drei Arten, die alle nach nichts aussehen - bis Stunden spaeter
der naechste Download rot wird. Genau diese drei Faelle sind unten
festgenagelt, und zwar gegen yt-dlps eigenen Lader: Was der nicht laden kann,
ist kaputt.
"""

from __future__ import annotations

from datetime import UTC, datetime, timedelta

import pytest

from app.services import cookies

KOPF = "# Netscape HTTP Cookie File\n# This file is generated by yt-dlp.  Do not edit.\n\n"

#: Ein Zeitpunkt weit in der Zukunft, damit die Tests nicht irgendwann von
#: selbst rot werden.
WEIT = int((datetime.now(UTC) + timedelta(days=90)).timestamp())


def zeile(name: str, wert: str = "x", ablauf: int | str = WEIT, domain: str = ".youtube.com") -> str:
    """Eine Zeile im Netscape-Format: 7 Felder, durch Tabulatoren getrennt."""
    return f"{domain}\tTRUE\t/\tTRUE\t{ablauf}\t{name}\t{wert}\n"


def datei(*namen: str, ablauf: int | str = WEIT) -> bytes:
    return (KOPF + "".join(zeile(n, ablauf=ablauf) for n in namen)).encode("utf-8")


#: Das Mindeste, was YouTube als Anmeldung durchgehen laesst - siehe
#: ``_has_auth_cookies`` im yt-dlp-Extractor.
GUELTIG = datei("LOGIN_INFO", "SAPISID", "HSID", "SSID")


@pytest.fixture(autouse=True)
def _ablage(tmp_path, monkeypatch):
    monkeypatch.setattr(cookies.settings, "data_dir", tmp_path)
    monkeypatch.setattr(cookies.settings, "ytdlp_cookies_file", None)
    return tmp_path


# ------------------------------------------------------------------ Pruefung


def test_angemeldete_datei_wird_angenommen(_ablage):
    befund = cookies.speichern(GUELTIG)
    assert befund.brauchbar
    assert befund.angemeldet
    assert "LOGIN_INFO" in befund.gefunden
    assert "SAPISID" in befund.gefunden
    assert befund.laeuft_ab is not None
    assert cookies.standardpfad().is_file()


def test_json_export_wird_erkannt(_ablage):
    """Der haeufigste Missgriff: Die Erweiterung exportiert JSON.

    yt-dlp wuerde nur "failed to load cookies" sagen - eine Meldung, aus der
    niemand ableiten kann, was zu tun ist.
    """
    befund = cookies.speichern(b'[{"domain": ".youtube.com", "name": "SID"}]')
    assert not befund.brauchbar
    assert "JSON" in befund.meldung
    assert "Netscape" in befund.meldung


def test_fehlende_kopfzeile_wird_erkannt(_ablage):
    """Ohne die Kopfzeile wirft Pythons MozillaCookieJar - und dann scheitert
    NICHT nur dieser Download, sondern jeder Aufruf an yt-dlp, auch das blosse
    Auflisten eines Kanals."""
    ohne_kopf = "".join(zeile(n) for n in ("LOGIN_INFO", "SAPISID")).encode("utf-8")
    befund = cookies.speichern(ohne_kopf)
    assert not befund.brauchbar
    assert "erste Zeile" in befund.meldung


def test_abgemeldet_exportierte_datei_wird_abgelehnt(_ablage):
    """Der heimtueckischste Fall: formal einwandfrei, aber ohne Anmeldung.

    Eine solche Datei wirkt exakt wie gar keine - man haelt das Problem fuer
    geloest und wundert sich, warum sich nichts aendert.
    """
    befund = cookies.speichern(datei("PREF", "VISITOR_INFO1_LIVE", "YSC"))
    assert not befund.brauchbar
    assert "keine Anmeldung" in befund.meldung
    assert "LOGIN_INFO" in befund.meldung


def test_login_info_allein_genuegt_nicht(_ablage):
    """yt-dlp verlangt LOGIN_INFO UND einen der SAPISID-Schluessel. Nur eines
    von beiden ist keine Anmeldung."""
    assert not cookies.speichern(datei("LOGIN_INFO")).brauchbar
    assert not cookies.speichern(datei("SAPISID")).brauchbar


def test_secure_3papisid_genuegt_als_ersatz(_ablage):
    """YouTube laesst SAPISID gelegentlich weg und liefert nur den
    3P-Schluessel - yt-dlp akzeptiert das, also muss der Assistent es auch."""
    befund = cookies.speichern(datei("LOGIN_INFO", "__Secure-3PAPISID"))
    assert befund.brauchbar, befund.meldung


def test_abgelaufene_anmeldung_wird_abgelehnt(_ablage):
    vergangen = int((datetime.now(UTC) - timedelta(days=1)).timestamp())
    befund = cookies.speichern(datei("LOGIN_INFO", "SAPISID", ablauf=vergangen))
    assert not befund.brauchbar
    assert "abgelaufen" in befund.meldung


def test_datei_ohne_youtube_cookies(_ablage):
    fremd = (KOPF + zeile("LOGIN_INFO", domain=".example.com")).encode("utf-8")
    befund = cookies.speichern(fremd)
    assert not befund.brauchbar
    assert "youtube.com" in befund.meldung


def test_leere_und_riesige_dateien(_ablage):
    assert "leer" in cookies.speichern(b"").meldung
    zu_gross = KOPF.encode() + b"#" * (cookies.MAX_BYTES + 1)
    assert not cookies.speichern(zu_gross).brauchbar


