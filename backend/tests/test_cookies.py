def test_kaputter_upload_laesst_die_gute_datei_stehen(_ablage):
    """Der wichtigste Test des Moduls.

    Wer eine funktionierende Anmeldung hinterlegt hat und danach versehentlich
    die falsche Datei hochlaedt, darf nicht schlechter dastehen als vorher. Ein
    kaputtes cookiefile legt jeden yt-dlp-Aufruf lahm - das waere der
    schlechteste denkbare Ausgang eines Fehlgriffs.
    """
    assert cookies.speichern(GUELTIG).brauchbar
    vorher = cookies.standardpfad().read_bytes()

    assert not cookies.speichern(b'{"nicht": "netscape"}').brauchbar

    assert cookies.standardpfad().read_bytes() == vorher
    assert cookies.pruefen().brauchbar


def test_keine_reste_nach_abgelehntem_upload(_ablage):
    cookies.speichern(b'{"nicht": "netscape"}')
    cookies.speichern(datei("PREF"))
    uebrig = [p.name for p in _ablage.iterdir() if p.name.startswith(".cookies-")]
    assert uebrig == [], f"Zwischendateien liegengeblieben: {uebrig}"


