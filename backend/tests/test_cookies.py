def test_hochgeladene_datei_landet_in_den_ytdlp_optionen(_ablage):
    from app.services import ytdlp

    assert "cookiefile" not in ytdlp._base_opts()
    cookies.speichern(GUELTIG)
    assert ytdlp._base_opts()["cookiefile"] == str(cookies.standardpfad())


def test_warnfrist(_ablage):
    bald = int((datetime.now(UTC) + timedelta(days=2)).timestamp())
    cookies.speichern(datei("LOGIN_INFO", "SAPISID", ablauf=bald))
    assert cookies.pruefen().als_dict()["bald_abgelaufen"] is True

    cookies.speichern(GUELTIG)  # 90 Tage
    assert cookies.pruefen().als_dict()["bald_abgelaufen"] is False


