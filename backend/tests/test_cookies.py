def test_ohne_datei_ist_nichts_hinterlegt(_ablage):
    assert cookies.aktiver_pfad() is None
    befund = cookies.pruefen()
    assert not befund.brauchbar
    assert "Keine Cookie-Datei" in befund.meldung


def test_hochgeladene_datei_wird_benutzt(_ablage):
    cookies.speichern(GUELTIG)
    assert cookies.aktiver_pfad() == cookies.standardpfad()


def test_eigener_pfad_sticht_die_hochgeladene(_ablage, monkeypatch):
    """Wer seine Datei selbst ins Volume legt, soll das weiter tun koennen -
    sonst waere der Assistent eine Verschlechterung fuer bestehende Aufbauten."""
    cookies.speichern(GUELTIG)
    eigen = _ablage / "eigene.txt"
    eigen.write_bytes(GUELTIG)
    monkeypatch.setattr(cookies.settings, "ytdlp_cookies_file", eigen)
    assert cookies.aktiver_pfad() == eigen


def test_gesetzter_aber_fehlender_pfad_faellt_nicht_auf_die_hochgeladene_zurueck(
    _ablage, monkeypatch
):
    """Bewusst kein Rueckfall: Wer einen Pfad ausdruecklich setzt, meint ihn.
    Still eine andere Datei zu nehmen waere die schlimmere Ueberraschung."""
    cookies.speichern(GUELTIG)
    monkeypatch.setattr(cookies.settings, "ytdlp_cookies_file", _ablage / "gibtsnicht.txt")
    assert cookies.aktiver_pfad() is None


def test_entfernen(_ablage):
    cookies.speichern(GUELTIG)
    assert cookies.entfernen() is True
    assert cookies.aktiver_pfad() is None
    assert cookies.entfernen() is False


